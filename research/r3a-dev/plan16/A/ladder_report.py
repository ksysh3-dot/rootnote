"""tables + mechanical decision from ladder_raw.json.   python ladder_report.py [ladder_raw.json] > ladder_report.txt"""
import json, sys
import numpy as np

raw = json.load(open(sys.argv[1] if len(sys.argv) > 1 else '/home/ksysh/r3a-dev/plan16/A/ladder_raw.json'))
res = raw['res']
SONGS = [k for k in res if k.startswith('Track')]
TRAIN = ['Track00060', 'Track00040', 'Track00001', 'Track00005', 'Track00012']
EVAL = ['Track00020', 'Track00023', 'Track00024', 'Track00025', 'Track00026']
ROWS = ['P1', 'R0', 'R1', 'R2', 'R3', 'R2s']
LADDER = ['R3', 'R2', 'R1', 'R0']
db = lambda x: 10 * np.log10(max(x, 1e-300))
meaning_of = lambda rn: {'R3': 'synthesis / band / weights', 'R2': 'amplitude attribution in the mix', 'R1': 'candidates and segmentation', 'R0': 'the selector'}[rn]


def pooled(rn, tn, f, keys=SONGS):
    return sum(res[k][rn][tn][f] for k in keys if res[k].get(rn))


E3 = {tn: pooled('R3', tn, 'E_right') for tn in ('v6b', 'strict')}
out = {}
print('# ladder report (generated by ladder_report.py from ladder_raw.json)')
print(f"songs with bass MIDI in 0-30 s: {[k for k in SONGS if res[k]['n_segments']]}; without: {[k for k in SONGS if not res[k]['n_segments']]}")
print('segments per song:', {k: res[k]['n_segments'] for k in SONGS}, ' gap attacks:', {k: res[k]['n_gap_attacks'] for k in SONGS})
print(f"pooled R3 right-layer energy (sum of y^2, t>0.5 s): {E3['v6b']:.4e}")

pre_all = {}
for rn in ROWS:
    g = []; l = []
    for k in SONGS:
        if res[k].get(rn):
            g += res[k][rn]['pre']['gap']; l += res[k][rn]['pre']['leg']
    pre_all[rn] = (np.array(g), np.array(l))
v5 = {rn: (res['t60_36_48'][rn]['v5a'] if res['t60_36_48'].get(rn) else None) for rn in ROWS}

table = {}
for tn in ('v6b', 'strict'):
    for rn in ROWS:
        Er = pooled(rn, tn, 'E_right') if rn != 'R1' or all(res[k]['R1'] for k in SONGS) else None
        if rn == 'R1':
            ks = [k for k in SONGS if res[k].get('R1')]; Er = pooled('R1', tn, 'E_right', ks); Ew = pooled('R1', tn, 'E_wrong', ks)
        else:
            Ew = pooled(rn, tn, 'E_wrong')
        gain2 = E3[tn] / Er if Er > 0 else float('nan')
        row = dict(E_right=Er, E_wrong=Ew, right_db_vs_R3=db(Er / E3[tn]), wrong_fd_fixed=Ew / E3[tn], wrong_fd_matched=Ew * gain2 / E3[tn], gain_db_matched=db(gain2) / 2 * 2 if np.isfinite(gain2) else float('nan'))
        g, l = pre_all[rn]
        row.update(v5a=None if v5[rn] is None else v5[rn]['frac'], pre_med=float(np.median(g)) if len(g) else float('nan'), pre_n=int(len(g)))
        table[(tn, rn)] = row

for tn in ('v6b', 'strict'):
    print(f"\n## energies and pass conditions, truth = {tn} ({'V6b any-note definition (primary)' if tn == 'v6b' else 'lowest bass note only (sensitivity)'})")
    print('row  | right dB vs R3 (fixed) | wrong/R3right fixed | wrong/R3right matched (gain dB) | V5a % | pre-echo dB (median gap attacks, N) | V6b wrong share %')
    for rn in ROWS:
        t = table[(tn, rn)]
        shares = {}
        ks = [k for k in SONGS if res[k].get(rn)]
        w = sum(res[k][rn][tn]['v6b_wrong'] for k in ks); r_ = sum(res[k][rn][tn]['v6b_right'] for k in ks)
        v6 = 100 * w / max(w + r_, 1e-30)
        e5 = [k for k in EVAL if k in ks]; w5 = sum(res[k][rn][tn]['v6b_wrong'] for k in e5); r5 = sum(res[k][rn][tn]['v6b_right'] for k in e5)
        t['v6b_share'] = v6; t['v6b_eval5'] = 100 * w5 / max(w5 + r5, 1e-30)
        print(f"{rn:3s} | {t['right_db_vs_R3']:8.2f} | {t['wrong_fd_fixed']:10.4f} | {t['wrong_fd_matched']:10.4f} ({t['gain_db_matched']:+.2f} dB) | "
              f"{'-' if t['v5a'] is None else format(100 * t['v5a'], '.1f')} | {t['pre_med']:+.2f} (N={t['pre_n']}) | {v6:.2f} (eval5 {t['v6b_eval5']:.2f})")
    # pass conditions and decision
    dec = {}
    for var in ('M', 'F'):
        flags = {}
        P1t = table[(tn, 'P1')]
        p1v = P1t['wrong_fd_matched'] if var == 'M' else P1t['wrong_fd_fixed']
        for rn in LADDER + ['R2s']:
            t = table[(tn, rn)]
            c1 = (t['wrong_fd_matched'] if var == 'M' else t['wrong_fd_fixed']) <= 0.5 * p1v
            c2 = True if var == 'M' else t['right_db_vs_R3'] >= -1.0
            c3 = t['v5a'] is not None and t['v5a'] <= 0.05
            c4 = t['pre_med'] <= 1.0
            flags[rn] = dict(c1=bool(c1), c2=bool(c2), c3=bool(c3), c4=bool(c4), passed=bool(c1 and c2 and c3 and c4))
        first_fail = next((rn for rn in LADDER if not flags[rn]['passed']), None)
        meaning = {'R3': 'synthesis / band / weights (R3 fails)', 'R2': 'amplitude attribution in the mix (R3 passes, R2 fails)',
                   'R1': 'candidates and segmentation (R2 passes, R1 fails)', 'R0': 'the selector (R1 passes, R0 fails)', None: 'none: all four rows pass'}[first_fail]
        dec[var] = (flags, first_fail, meaning)
        print(f"\n  variant {var} ({'matched gain' if var == 'M' else 'fixed gain'}): P1 reference wrong/R3right = {p1v:.4f}; limit (0.5x) = {0.5 * p1v:.4f}")
        for rn in LADDER + ['R2s']:
            f = flags[rn]
            print(f"    {rn:3s} cond1 {'Y' if f['c1'] else 'n'}  cond2 {'Y' if f['c2'] else 'n'}  cond3(V5a<=5%) {'Y' if f['c3'] else 'n'}  cond4(pre<=1dB) {'Y' if f['c4'] else 'n'}  -> {'PASS' if f['passed'] else 'fail'}")
        print(f"    DECISION ({var}, truth {tn}): first failing row from R3 downward = {first_fail}  ->  bottleneck: {meaning}")
        ff3 = next((rn for rn in LADDER if not (flags[rn]['c1'] and flags[rn]['c2'] and flags[rn]['c4'])), None)
        print(f"    (sensitivity, NOT the specified rule: conditions 1, 2, 4 only, i.e. ignoring V5a) first failing row = {ff3}  ->  {ff3 and meaning_of(ff3)}")
    out[tn] = {v: dict(first_fail=dec[v][1], meaning=dec[v][2], flags=dec[v][0]) for v in dec}

# eval-5 only (R0's classifier is in-sample on the TRAIN-5): fixed-denominator wrong ratio, truth v6b
print('\n## EVAL-5 songs only (classifier out-of-sample), truth v6b: wrong energy / R3 right energy of the same songs (fixed gain), right dB vs R3')
e5 = [k for k in EVAL if res[k]['n_segments']]
E3e = sum(res[k]['R3']['v6b']['E_right'] for k in e5)
for rn in ('P1', 'R0', 'R1', 'R2', 'R3'):
    ke = [k for k in EVAL if res[k].get(rn)]
    ew = sum(res[k][rn]['v6b']['E_wrong'] for k in ke); er = sum(res[k][rn]['v6b']['E_right'] for k in e5 if res[k].get(rn))
    print(f"{rn:3s} wrong/R3right {ew / E3e:.4f}   right vs R3 {db(er / E3e):+.2f} dB   (songs with bass: {e5}; wrong energy over all 5 EVAL songs)")

# per-song tables
print('\n## per song (truth v6b): right layer dB vs R3 / fixed-denominator wrong ratio (wrong energy / that song R3 right energy) / V6b wrong share %')
for rn in ['P1', 'R0', 'R1', 'R2', 'R3', 'R2s']:
    cells = []
    for k in SONGS:
        t = res[k].get(rn); r3 = res[k]['R3']['v6b']['E_right']
        if not t or r3 <= 0:
            cells.append(f"{k[-2:]}: n/a(no bass)" if r3 <= 0 and t else f"{k[-2:]}: -"); continue
        sh = 100 * t['v6b']['v6b_wrong'] / max(t['v6b']['v6b_wrong'] + t['v6b']['v6b_right'], 1e-30)
        cells.append(f"{k[-2:]}: {db(t['v6b']['E_right'] / r3):+.1f}dB/{t['v6b']['E_wrong'] / r3:.3f}/{sh:.1f}%")
    print(rn.ljust(3), ' | '.join(cells))
print('songs without bass MIDI (R3 right energy 0): wrong energy of each row (absolute, same units):')
for k in SONGS:
    if not res[k]['n_segments']:
        print(' ', k, {rn: round(res[k][rn]['v6b']['E_wrong'], 6) if res[k].get(rn) else None for rn in ROWS})

# pre-echo detail
print('\n## pre-echo (rise dB, plain form): gap attacks median / p90 / N ; legato attacks median / N ; excess over R3 (median of per-attack row-R3, gap attacks)')
r3g = pre_all['R3'][0]
for rn in ROWS:
    g, l = pre_all[rn]
    ex = np.median(g - r3g) if len(g) == len(r3g) and len(g) else float('nan')
    print(f"{rn:3s} gap: median {np.median(g):+.2f} p90 {np.percentile(g, 90):+.2f} N={len(g)} | legato: median {np.median(l) if len(l) else float('nan'):+.2f} N={len(l)} | excess vs R3 {ex:+.2f}")

# V5a
print('\n## V5a on the T60 36-48 s excerpt (drops/n):', {rn: (None if v5[rn] is None else f"{v5[rn]['drops']}/{v5[rn]['n']}") for rn in ROWS})

# R2 information
print(f"\n## information: energy of (R2 layer - R3 layer) relative to R3 layer, pooled 10 songs: {10 * np.log10(raw['diff_R2_R3_energy_over_R3']):.2f} dB")
print('\n## R2 MIDI boundary vs stem activity (segments pooled over the 10 songs; d = stem - MIDI, ms)')
don = []; doff = []; act = []; att = []; dur = []
for k, s in raw['stem'].items():
    if k.startswith('Track'):
        don += s['d_on_ms']; doff += s['d_off_ms']; act += s['active']; att += s['attack']; dur += s['dur_ms']
don = np.array(don); doff = np.array(doff); act = np.array(act, bool); att = np.array(att, bool); dur = np.array(dur)
q = lambda a: [round(float(x), 1) for x in np.percentile(a, [10, 25, 50, 75, 90])] if len(a) else None
print(f"segments N={len(don)} (attack segments {int(att.sum())}); no stem activity (<= -40 dB re song p95): {int((~act).sum())} ({100 * (~act).mean():.1f}%)")
print('d_on  (stem on - MIDI start) p10/25/50/75/90, active segments:', q(don[act]))
print('d_off (stem off - MIDI end)  p10/25/50/75/90, active segments:', q(doff[act]))
print('d_on on attack segments only:', q(don[act & att]), ' segments with stem on earlier than MIDI start by > 10 ms:', f"{100 * np.mean(don[act] < -10):.1f}%", ' later by > 10 ms:', f"{100 * np.mean(don[act] > 10):.1f}%")
print('d_off: stem keeps sounding > 50 ms after MIDI end:', f"{100 * np.mean(doff[act] > 50):.1f}%", ' ends > 50 ms before MIDI end:', f"{100 * np.mean(doff[act] < -50):.1f}%")
print('R2 (MIDI interval) vs R2s (stem-activity interval) rows are in the tables above (R2s = information).')

json.dump(dict(table={f'{a}|{b}': v for (a, b), v in table.items()}, decisions=out), open('/home/ksysh/r3a-dev/plan16/A/ladder_summary.json', 'w'), indent=1, default=float)
